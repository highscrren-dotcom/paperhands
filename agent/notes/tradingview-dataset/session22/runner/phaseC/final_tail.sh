#!/bin/bash
# Всё, что нужно посчитать ПОСЛЕ прогона, одной командой.
# Конвейер сам собирает панели и сводку (pipeline_c.sh), здесь — то, что сверх этого:
#   1) сверка угла движка с питоновскими контролями уже на полных данных;
#   2) парный бета-контроль на НАСТОЯЩЕМ правиле рецепта, на коротком и длинном холде,
#      чтобы закрыть последнюю оговорку отчёта («контроли считались в углу сетки»);
#   3) сводка по сетке ещё раз — на случай, если конвейер её не дописал.
# Идемпотентен, ничего не портит: пишет только в свои out-файлы.
set -u
ROOT=/data/backtests/_agent/phaseA
CROOT=/data/backtests/_agent/phaseC
P="${1:-$CROOT/panel_c}"
N() { nice -n 19 ionice -c3 "$@"; }

[ -d "$P" ] || { echo "нет панели $P — конвейер ещё не собрал"; exit 1; }

echo "=== 1. СВЕРКА С ДВИЖКОМ НА ПОЛНЫХ ДАННЫХ ==="
N python3 "$CROOT/xcheck.py" "$P"

echo
echo "=== 2. ПАРНЫЙ БЕТА-КОНТРОЛЬ НА ПРАВИЛЕ РЕЦЕПТА (лок 20 / стоп 99 / трейл 8) ==="
for H in 20160 25920 38880; do
  echo "--- холд $((H / 1440)) сут ---"
  N python3 "$CROOT/paired_rule.py" "$P" "$H" 20 99 8 2 10
  echo
done

echo "=== 3. СВОДКА ПО СЕТКЕ ==="
N python3 "$ROOT/summary.py" "$P" "C-hold27"
