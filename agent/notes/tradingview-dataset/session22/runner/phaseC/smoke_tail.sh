#!/bin/bash
# Прогон ХВОСТА конвейера на том, что уже посчитано, — до того как прогон кончится.
# Смысл: concat -> sweep -> summary отрабатывают в самом конце, и ошибка в них
# обнаружится в момент, когда переделывать уже нечем. Здесь та же цепочка гоняется
# на частичных данных в отдельный каталог, ничего не задевая.
# Заодно делается то, что иначе пришлось бы делать отдельно:
#   - сверка угла движка (лок 0 / стоп 99 / трейл 100) с питоновскими контролями
#     уже на всём датасете, а не на одном тикеро-месяце;
#   - парный бета-контроль на НАСТОЯЩЕМ правиле рецепта (лок 20 / трейл 8 / стопа нет).
# usage: smoke_tail.sh [панель]
set -u
ROOT=/data/backtests/_agent/phaseA
CROOT=/data/backtests/_agent/phaseC
P="${1:-$CROOT/panel_smoke}"
N() { nice -n 19 ionice -c3 "$@"; }

echo "=== сборка панелей из $(ls "$CROOT/out_c" | grep -c '^done_') закрытых задач ==="
N "$ROOT/concat.sh" "$CROOT/out_c" "$P"

echo
echo "=== лифт отбора по каждому правилу ==="
N python3 "$ROOT/sweep.py" "$P"

echo
echo "=== сводка по сетке ==="
N python3 "$ROOT/summary.py" "$P" "C-частичная"

echo
echo "=== СВЕРКА: угол движка против питоновских контролей на всём датасете ==="
N python3 "$CROOT/xcheck.py" "$P"
