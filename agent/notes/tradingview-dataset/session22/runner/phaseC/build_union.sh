#!/bin/bash
# Объединённый склад свечей на символ: жёсткие ссылки со всех месячных пакетов.
#
# Зачем: кэш Петра нарезан по месяцам, и окно каждого пакета кончается через 14 суток
# после последней идеи месяца. Для холда 27 суток не хватает 13 суток на пакет — но почти
# всё это уже лежит в СОСЕДНЕМ месячном пакете того же символа, просто в другом каталоге,
# а движок видит только кэш своего месяца (путь ./dump/... относительно cwd).
#
# Жёсткие ссылки не занимают места: это записи в каталоге, данные общие с оригиналом.
# Данные Петра при этом остаются нетронутыми — мы только читаем и ссылаемся.
set -u
SYM="$1"
SRC=/data/backtests/dataset-master/content
DST=/data/backtests/_agent/phaseC/union/$SYM/dump/data/candle/ccxt_cached/$SYM/1m
mkdir -p "$DST"
t0=$(date +%s)
n=0
for d in "$SRC"/*/dump/data/candle/ccxt_cached/"$SYM"/1m; do
  [ -d "$d" ] || continue
  cp -aln "$d/." "$DST/" 2>/dev/null
  n=$((n + 1))
done
cnt=$(ls "$DST" | wc -l)
echo "$SYM: пакетов $n, файлов в складе $cnt, за $(( $(date +%s) - t0 )) с"
